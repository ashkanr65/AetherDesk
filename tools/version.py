"""Synchronize the source-owned release version without building the application."""

import argparse
import hashlib
import json
import re
from pathlib import Path


def release(root):
    data = json.loads((root / "release.json").read_text(encoding="utf-8-sig"))
    if not isinstance(data, dict):
        raise ValueError("release.json must contain a JSON object")
    version = data.get("version", "")
    if not isinstance(version, str) or not re.fullmatch(
        r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:\.(0|[1-9][0-9]*))?", version
    ):
        raise ValueError("release.json version must be major.minor or major.minor.patch, e.g. 0.2")
    build = data.get("build")
    if type(build) is not int or not 1 <= build <= 65535:
        raise ValueError("release.json build must be an integer from 1 to 65535")
    parts = [int(part) for part in version.split(".")]
    if any(part > 65535 for part in parts):
        raise ValueError("Version components must be at most 65535 for Windows")
    normalized = ".".join(str(part) for part in parts + [0] * (3 - len(parts)))
    return version, normalized, build


def replace_once(pattern, replacement, text, label, flags=0):
    updated, count = re.subn(pattern, replacement, text, flags=flags)
    if count != 1:
        raise ValueError(f"Expected exactly one {label}; found {count}")
    return updated


def sync(root, check=False):
    version, normalized, build = release(root)
    # The native client keeps Flutter files as immutable migration evidence.
    # Their historical version is not the shipped native application's version.
    migration = root / "rust-migration.json"
    frozen = {}
    if migration.exists():
        frozen = {
            entry["path"]: entry["sha256"].lower()
            for entry in json.loads(migration.read_text(encoding="utf-8-sig")).get("referenceFiles", [])
        }
    for relative in ("ui/flutter/ad_remote_desktop/pubspec.yaml",
                     "ui/flutter/ad_remote_desktop/lib/app_version.dart"):
        if relative in frozen:
            path = root / relative
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != frozen[relative]:
                raise ValueError("Frozen migration reference changed; restore its recorded content: " + relative)
    cargo = root / "core/rust/Cargo.toml"
    changes = {
        cargo: replace_once(
            r'(\[workspace.package\]\s*\nversion\s*=\s*)"[^"]+"',
            lambda match: match[1] + '"' + normalized + '"',
            cargo.read_text(encoding="utf-8"),
            "Cargo workspace version",
        )
    }
    native = root / "ui/rust/Cargo.toml"
    if native.exists():
        changes[native] = replace_once(
            r'(\[workspace.package\]\s*\nversion\s*=\s*)"[^"]+"',
            lambda match: match[1] + '"' + normalized + '"',
            native.read_text(encoding="utf-8"), "Native UI workspace version",
        )
    pub = root / "ui/flutter/ad_remote_desktop/pubspec.yaml"
    if pub.relative_to(root).as_posix() not in frozen:
        changes[pub] = replace_once(
            r"^version:.*$", f"version: {normalized}+{build}",
            pub.read_text(encoding="utf-8"), "Flutter version", re.M,
        )
    generated = root / "ui/flutter/ad_remote_desktop/lib/app_version.dart"
    if generated.relative_to(root).as_posix() not in frozen:
        changes[generated] = (
            "// Generated by tools/version.py from release.json.\n"
            f"const appVersion = '{version}';\n"
            f"const agentVersion = '{normalized}';\n"
            f"const appBuild = {build};\n"
        )
    # Only crates inheriting workspace.package.version follow this release.
    names = set()
    for manifest in (root / "core/rust/crates").glob("*/Cargo.toml"):
        text = manifest.read_text(encoding="utf-8")
        package = re.search(r"\[package\]\s*\n(.*?)(?=\n\[|\Z)", text, re.S)
        if not package or not re.search(r"^version\.workspace\s*=\s*true\s*$", package[1], re.M):
            continue
        name = re.search(r'^name\s*=\s*"([^"]+)"', package[1], re.M)
        if name:
            names.add(name[1])
    lock = root / "core/rust/Cargo.lock"
    if not lock.exists():
        raise ValueError("core/rust/Cargo.lock is required for locked builds")
    blocks = lock.read_text(encoding="utf-8").split("[[package]]")
    replaced = {}
    for index, block in enumerate(blocks[1:], 1):
        name = re.search(r'^name = "([^"]+)"', block, re.M)
        old_version = re.search(r'^version = "([^"]+)"', block, re.M)
        if name and name[1] in names and not re.search(r"^source\s*=", block, re.M):
            if not old_version:
                raise ValueError(f"Missing lockfile version for {name[1]}")
            replaced[(name[1], old_version[1])] = normalized
            blocks[index] = replace_once(
                r'^version = "[^"]+"', f'version = "{normalized}"', block,
                f"lockfile version for {name[1]}", re.M,
            )
    lock_text = "[[package]]".join(blocks)
    for (name, old_version), new_version in replaced.items():
        # Cargo disambiguates same-named packages in dependency entries with a version.
        # Registry entries have a source suffix and must remain untouched.
        lock_text = lock_text.replace(f' "{name} {old_version}",', f' "{name} {new_version}",')
    changes[lock] = lock_text
    stale = [
        path for path, content in changes.items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    if check and stale:
        raise ValueError("Version files need synchronization: " + ", ".join(str(path.relative_to(root)) for path in stale))
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as destination:
            destination.write(changes[path])
    return {"version": version, "normalized": normalized, "build": build}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--show", action="store_true")
    args = parser.parse_args()
    try:
        if args.show:
            v, n, b = release(args.root)
            print(json.dumps({"version": v, "normalized": n, "build": b}))
        else:
            print(json.dumps(sync(args.root, args.check)))
    except (ValueError, OSError) as error:
        parser.exit(1, f"Release version: {error}\n")
